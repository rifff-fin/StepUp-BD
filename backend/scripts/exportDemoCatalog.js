// Writes the seed catalog + store settings to frontend/src/content/demoCatalog.json.
// The frontend falls back to this snapshot when the API cannot be reached (e.g. the Netlify
// site is live before the Render API, or the free-tier server is asleep), so the store is
// never empty. Run again after editing data/:   npm run export:demo
const fs = require('fs');
const path = require('path');
const products = require('../data/products');
const coupons = require('../data/coupons');
const options = require('../data/catalogOptions');
const { DIVISIONS } = require('../data/districts');
const { DELIVERY_FEES, DELIVERY_DAYS, MAX_QTY_PER_LINE } = require('../services/pricingService');

const OUT = path.join(__dirname, '..', '..', 'frontend', 'src', 'content', 'demoCatalog.json');

const discountPercent = (p) =>
  p.originalPrice > p.price ? Math.round((1 - p.price / p.originalPrice) * 100) : 0;

const snapshot = {
  note: 'Generated by backend/scripts/exportDemoCatalog.js. Do not edit by hand.',
  products: products.map((p) => ({
    ...p,
    discountPercent: discountPercent(p),
    createdAt: p.createdAt.toISOString(),
  })),
  coupons: coupons.filter((c) => c.active).map(({ code, percent }) => ({ code, percent })),
  meta: {
    brands: options.BRANDS,
    categories: options.CATEGORIES,
    colors: options.COLORS,
    sizes: options.SIZES,
    priceRange: options.PRICE_RANGE,
    currency: options.CURRENCY,
    divisions: DIVISIONS,
    delivery: { fees: DELIVERY_FEES, days: DELIVERY_DAYS },
    maxQtyPerLine: MAX_QTY_PER_LINE,
  },
};

fs.writeFileSync(OUT, `${JSON.stringify(snapshot, null, 2)}\n`);
console.log(
  `✅ Wrote ${snapshot.products.length} products to ${path.relative(process.cwd(), OUT)}`,
);
